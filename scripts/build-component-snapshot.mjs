#!/usr/bin/env node
// Builds a standalone static Storybook bundle containing only ONE
// component's stories (instead of the whole library).
//
// Use case: embedding a frozen, live-navigable Storybook preview of a
// single component in an external site (e.g. an iframe in gradaigh-astro)
// without dragging in every other component, and without that preview
// silently changing as work continues on the component afterward here.
//
// How it works: Storybook's `stories` glob in .storybook/main.ts can't be
// overridden via CLI flag, so this script writes a temporary sibling config
// dir (.storybook-snapshot/, same depth as .storybook/ so its relative
// "../src" glob still resolves) that re-exports the real config with
// `stories` narrowed to just the target component's *.stories.tsx, runs
// `storybook build` against it, then deletes the temp config dir.
//
// Usage:
//   node scripts/build-component-snapshot.mjs <ComponentName>
//   pnpm snapshot:component Accordion
//
// Output: snapshots/<ComponentName>/ at the repo root (gitignored — this is
// a build artifact, not source). To actually use a snapshot, either:
//   - copy that one output dir into wherever the consuming site's static
//     assets live (e.g. gradaigh-astro/public/storybook-snapshots/Accordion/)
//     and iframe it from there, or
//   - host it (GitHub Pages, Chromatic, etc.) and iframe the hosted URL.
//
// Embedding: iframe.html shows nothing on its own — it has no story
// selected until Storybook's manager UI (index.html) tells it which one via
// a URL param. Either iframe index.html itself (full Storybook chrome, lets
// visitors switch between this component's stories), or iframe.html with an
// explicit story id, e.g.:
//   iframe.html?id=components-accordion--default&viewMode=story
// Story ids are listed in the build output's index.json.
//
// For reproducibility, run this against a tagged commit
// (e.g. `git tag accordion-v1-snapshot`) rather than an arbitrary work-in-
// progress commit, so the frozen preview's provenance is traceable later.
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

const componentName = process.argv[2];
if (!componentName) {
  console.error('Usage: node scripts/build-component-snapshot.mjs <ComponentName>');
  process.exit(1);
}

const searchRoots = ['src/primitives', 'src/components'];
const componentDir = searchRoots
  .map((root) => join(repoRoot, root, componentName))
  .find((dir) => existsSync(dir));

if (!componentDir) {
  console.error(
    `Could not find "${componentName}" under ${searchRoots.join(' or ')}. ` +
      'Pass the directory name exactly as it appears there (case-sensitive).',
  );
  process.exit(1);
}

const storiesGlob = `../${relative(repoRoot, componentDir)}/*.stories.@(js|jsx|mjs|ts|tsx)`;

// Lives at repo root, alongside .storybook/, so its own "../src" imports
// inside main.ts resolve exactly as they do for the real config.
const snapshotConfigDir = join(repoRoot, '.storybook-snapshot');
const outputDir = join(repoRoot, 'snapshots', componentName);

rmSync(snapshotConfigDir, { recursive: true, force: true });
mkdirSync(snapshotConfigDir, { recursive: true });

writeFileSync(
  join(snapshotConfigDir, 'main.ts'),
  `import baseConfig from '../.storybook/main';

// Generated by scripts/build-component-snapshot.mjs — do not edit by hand,
// and do not commit (this whole directory is gitignored).
const config = {
  ...baseConfig,
  stories: ['${storiesGlob}'],
};
export default config;
`,
);

// preview.tsx carries global decorators/parameters (fonts, theme, etc.) —
// reuse it unmodified so the snapshot renders identically to the real
// Storybook rather than a bare, unstyled version of the component.
writeFileSync(
  join(snapshotConfigDir, 'preview.tsx'),
  `export { default } from '../.storybook/preview';\n`,
);

console.log(`Building isolated snapshot for "${componentName}" -> ${relative(repoRoot, outputDir)}`);

const result = spawnSync(
  'pnpm',
  ['exec', 'storybook', 'build', '--config-dir', '.storybook-snapshot', '--output-dir', relative(repoRoot, outputDir)],
  { cwd: repoRoot, stdio: 'inherit' },
);

rmSync(snapshotConfigDir, { recursive: true, force: true });

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

console.log(`Done. Static snapshot at ${relative(repoRoot, outputDir)}/ — copy or host this directory, then iframe it.`);
